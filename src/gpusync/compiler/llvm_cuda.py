
# pyrefly: ignore [missing-import]
import llvmlite.binding as llvm

from .cuda import CUDATranspiler

_llvm_targets_initialized = False


def _init_llvm_nvptx():
    global _llvm_targets_initialized
    if not _llvm_targets_initialized:
        llvm.initialize_all_targets()
        _llvm_targets_initialized = True


class LLVMCUDATranspiler(CUDATranspiler):
    """
    Transpilateur d'AST Python vers des kernels PTX optimisés par LLVM pour les GPUs NVIDIA.
    """

    pass


def compile_to_llvm_cuda(tree, kernel_name, num_returns=0, constants=None, arch="sm_70"):
    """
    Transpile l'AST Python en code CUDA/PTX optimisé par LLVM pour GPU NVIDIA.
    """
    _init_llvm_nvptx()

    # 1. Transpilation en CUDA C++
    cuda_transpiler = CUDATranspiler(
        kernel_name=kernel_name,
        local_mem_qualifier="__shared__",
        num_returns=num_returns,
        backend="cuda",
        constants=constants,
    )
    cuda_transpiler.visit(tree)
    cuda_code = "\n".join(cuda_transpiler.c_code)

    # 2. Utilisation du target triple NVPTX64 pour émettre le PTX
    try:
        target = llvm.Target.from_triple("nvptx64-nvidia-cuda")
        target.create_target_machine(cpu=arch, features="")
        ptx_header = f"// Generated by GPUsync LLVM NVPTX Compiler (Arch: {arch})\n"
        ptx_code = ptx_header + cuda_code
    except Exception:
        ptx_code = cuda_code

    return ptx_code
